/**
 * publish: pushes one woven kit to GitHub as a new public repository, then removes the
 * local build and spec to save disk space. The small <slug>.meta.json is kept for the
 * database insert.
 *
 *   node scripts/kits/publish.mjs <slug>
 *
 * The GitHub token is read from %USERPROFILE%\.config\kitloom\github-token(.txt). It is
 * never printed, never written to git config or a remote URL: git receives it only through
 * environment variables for the single push.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../../discovery/kits/", import.meta.url));
const slug = process.argv[2];
if (!slug) throw new Error("Usage: node scripts/kits/publish.mjs <slug>");
const BUILD = join(ROOT, "build", slug);
const META = join(ROOT, "build", `${slug}.meta.json`);
if (!existsSync(BUILD) || !existsSync(META)) throw new Error(`${slug}: not built — run weave.mjs first`);
const meta = JSON.parse(readFileSync(META, "utf8"));
if (meta.heddle.verdict === "caution" || meta.heddle.verdict === "danger") throw new Error(`${slug}: Heddle ${meta.heddle.verdict}; not publishing`);

const tokenFile = ["github-token", "github-token.txt"].map((n) => join(process.env.USERPROFILE ?? "", ".config", "kitloom", n)).find(existsSync);
if (!tokenFile) throw new Error("No token file in %USERPROFILE%\\.config\\kitloom\\");
const token = readFileSync(tokenFile, "utf8").replace(/^﻿/, "").trim();

async function github(method, path, body) {
  const response = await fetch(`https://api.github.com${path}`, {
    method,
    headers: { Authorization: `Bearer ${token}`, Accept: "application/vnd.github+json", "User-Agent": "kitloom-publisher", "X-GitHub-Api-Version": "2022-11-28" },
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await response.text();
  return { status: response.status, json: text ? JSON.parse(text) : null };
}

const me = await github("GET", "/user");
if (me.status !== 200) throw new Error(`GitHub token rejected (${me.status})`);
const owner = me.json.login;
if (!meta.repository_url.startsWith(`https://github.com/${owner}/`)) throw new Error(`${slug}: meta points at another owner`);

// 1. Repository
const existing = await github("GET", `/repos/${owner}/${slug}`);
if (existing.status === 404) {
  const created = await github("POST", "/user/repos", {
    name: slug,
    description: meta.description.slice(0, 350),
    homepage: "https://kitloom.site",
    private: false,
    has_issues: true,
    has_projects: false,
    has_wiki: false,
    auto_init: false,
  });
  if (created.status !== 201) throw new Error(`${slug}: could not create repository (${created.status}: ${created.json?.message ?? ""})`);
} else if (existing.status !== 200) {
  throw new Error(`${slug}: could not check repository (${existing.status})`);
} else if (existing.json.size > 0) {
  throw new Error(`${slug}: repository already has content; refusing to overwrite`);
}

// 2. Commit and push. Identity is the account's private noreply address.
const git = (...args) =>
  execFileSync("git", ["-C", BUILD, "-c", "credential.helper=", "-c", "core.autocrlf=false", ...args], {
    stdio: ["ignore", "pipe", "pipe"],
    env: {
      ...process.env,
      GIT_TERMINAL_PROMPT: "0",
      GIT_CONFIG_COUNT: "1",
      GIT_CONFIG_KEY_0: "http.https://github.com/.extraheader",
      GIT_CONFIG_VALUE_0: `AUTHORIZATION: basic ${Buffer.from(`x-access-token:${token}`).toString("base64")}`,
    },
  }).toString();

rmSync(join(BUILD, ".git"), { recursive: true, force: true });
git("init", "-q", "-b", "main");
git("add", "-A");
git(
  "-c", "user.name=Kitloom",
  "-c", `user.email=${me.json.id}+${owner}@users.noreply.github.com`,
  "commit", "-q", "-m", `${meta.name} 1.0.0\n\nGenerated by Kitloom for every major coding agent. Skills keep their original licences; see THIRD_PARTY_NOTICES.md.`,
);
git("remote", "add", "origin", `https://github.com/${owner}/${slug}.git`);
try {
  git("push", "-q", "-u", "origin", "main");
} catch (error) {
  // stderr may echo the remote URL but never the token (it is only in an env var).
  throw new Error(`${slug}: push failed: ${String(error.stderr ?? error.message).split("\n").slice(0, 3).join(" ")}`);
}
const commit = git("rev-parse", "HEAD").trim();

// 3. Topics, so people browsing GitHub can find the kits.
const topics = [...new Set(["kitloom", "agent-setup", "agents-md", "agent-skills", "claude-code", "codex", "cursor", ...meta.tags])]
  .filter((t) => /^[a-z0-9][a-z0-9-]{0,49}$/.test(t))
  .slice(0, 20);
await github("PUT", `/repos/${owner}/${slug}/topics`, { names: topics });

// 4. Confirm GitHub has it, record the commit, free the disk.
const remote = await github("GET", `/repos/${owner}/${slug}/commits/main`);
if (remote.status !== 200 || remote.json.sha !== commit) throw new Error(`${slug}: pushed commit not visible on GitHub yet`);
writeFileSync(META, JSON.stringify({ ...meta, commit }, null, 2));
rmSync(BUILD, { recursive: true, force: true });
rmSync(join(ROOT, "specs", slug), { recursive: true, force: true });
console.log(`${slug}: published https://github.com/${owner}/${slug} at ${commit.slice(0, 7)}; local build and spec removed`);
